import { chromium } from '../web/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { mkdir,writeFile } from 'node:fs/promises';
const origin='https://zoom-connect-tpg-demo.fly.dev';
const artifacts='ephemeral/scheduled-hosted-proof';
await mkdir(artifacts,{recursive:true});
const browser=await chromium.launch({headless:true});
let response,controller;
try {
 const context=await browser.newContext({viewport:{width:1360,height:1000},timezoneId:'America/Costa_Rica'});
 const login=await context.request.post(origin+'/api/login',{data:{email:process.env.DEMO_LOGIN_EMAIL,password:process.env.DEMO_LOGIN_PASSWORD}});
 assert.equal(login.status(),200,'hosted password login');
 assert.equal((await context.request.get(origin+'/api/demo/users')).status(),404,'simulated users remain disabled');
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin+'/calls');
 await page.getByRole('button',{name:'Add scheduled call',exact:true}).click();
 const meetingID='9'+Date.now().toString().slice(-10);
 await page.getByLabel('Zoom invitation or meeting link').fill(`https://zoom.us/j/${meetingID}`);
 await page.getByLabel('Call title').fill('Deployment verification: scheduled client connection');
 await page.getByRole('button',{name:'Add call',exact:true}).click();
 await page.getByRole('heading',{name:'Ready for clients to connect'}).waitFor();
 const id=new URL(page.url()).pathname.split('/').at(-1);
 const metadata=await (await context.request.get(origin+'/api/calls/'+id)).json();
 assert.equal(metadata.status,'scheduled');assert.equal(metadata.started,null);assert.equal(metadata.zoom_meeting_id,meetingID);
 await page.getByText('Connected · waiting for the meeting',{exact:true}).waitFor();
 await page.screenshot({path:artifacts+'/waiting.png',fullPage:true,animations:'disabled'});
 controller=new AbortController();
 response=await fetch(origin+`/api/calls/${id}/stream`,{headers:{Authorization:'Bearer '+process.env.ZOOM_CONNECT_KEY},signal:controller.signal});
 assert.equal(response.status,200);
 const reader=response.body.getReader();let received='';
 const drain=(async()=>{for(;;){const{done,value}=await reader.read();if(done)break;received+=new TextDecoder().decode(value);}})();
 const waitFor=async text=>{const deadline=Date.now()+20000;while(!received.includes(text)){if(Date.now()>deadline)throw Error('missing '+text);await new Promise(r=>setTimeout(r,60));}};
 await waitFor('event: call.scheduled');await waitFor(': keepalive');
 await page.getByRole('button',{name:'Cancel scheduled call',exact:true}).click();
 await page.getByText('Scheduled call cancelled',{exact:true}).waitFor();
 await waitFor('event: end');await drain;
 assert(received.includes('event: call.cancelled'));assert(!received.includes('event: transcript'));
 const health=await (await context.request.get(origin+'/healthz')).json();assert.equal(health.status,'ok');
 assert.deepEqual(errors,[]);
 const result={origin,at:new Date().toISOString(),callID:id,health,clientConnectedBeforeStart:true,keepalive:true,cancellationEndedClientStream:true,simulatedZoomInput:false,realZoomOpeningCaptureTested:false,browserErrors:errors};
 await writeFile(artifacts+'/result.json',JSON.stringify(result,null,2)+'\n');
 await writeFile(artifacts+'/client-stream.txt',received.trimEnd()+'\n');
 console.log(JSON.stringify(result,null,2));
} finally {controller?.abort();await browser.close();}
