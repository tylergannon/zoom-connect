import { chromium } from '../web/node_modules/playwright/index.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const origin = 'http://127.0.0.1:8094';
const artifacts = 'ephemeral/scheduled-proof';
await mkdir(artifacts,{recursive:true});
const browser = await chromium.launch({ headless:true });
const errors=[];
try {
 const context=await browser.newContext({ viewport:{width:1360,height:1000} });
 const login=await context.request.post(origin+'/api/demo/login',{data:{email:'dana@acme.co'}});
 assert.equal(login.status(),200);
 const page=await context.newPage();
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(origin+'/calls');
 await page.getByRole('button',{name:'Add scheduled call',exact:true}).click();
 const meetingID='8'+Date.now().toString().slice(-10);
 await page.getByLabel('Zoom invitation or meeting link').fill(`Join Zoom Meeting\nhttps://us02web.zoom.us/j/${meetingID}?pwd=not-persisted\nMeeting ID: ${meetingID}`);
 await page.getByLabel('Call title').fill('Scheduled client stream proof');
 await page.getByLabel('Expected start').fill('2026-10-20T09:00');
 await page.screenshot({animations:'disabled',path:artifacts+'/add-call.png'});
 await page.getByRole('button',{name:'Add call',exact:true}).click();
 await page.getByRole('heading',{name:'Ready for clients to connect'}).waitFor();
 const callID=new URL(page.url()).pathname.split('/').at(-1);
 await page.getByText('Connected · waiting for the meeting',{exact:true}).waitFor();
 await page.screenshot({animations:'disabled',path:artifacts+'/waiting.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({animations:'disabled',path:artifacts+'/waiting-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > window.innerWidth),false,'mobile overflow');
 await page.setViewportSize({width:1360,height:1000});
 await page.goto(origin+'/calls');
 await page.getByRole('heading',{name:'Upcoming',exact:true}).waitFor();
 await page.locator(`a[href="/calls/${callID}"]`).click();
 await page.getByRole('heading',{name:'Ready for clients to connect'}).waitFor();
 const keyResponse=await context.request.post(origin+'/api/keys',{data:{name:'scheduled-proof-client'}});
 const key=await keyResponse.json();
 const controller=new AbortController();
 const response=await fetch(origin+`/api/calls/${callID}/stream`,{headers:{Authorization:`Bearer ${key.secret}`},signal:controller.signal});
 assert.equal(response.status,200);
 const reader=response.body.getReader();
 let received='';
 const drain=(async()=>{const decoder=new TextDecoder();for(;;){const {value,done}=await reader.read();if(done)break;received+=decoder.decode(value,{stream:true});}})();
 const waitFor=async text=>{const deadline=Date.now()+10000;while(!received.includes(text)){if(Date.now()>deadline)throw Error('missing '+text);await new Promise(resolve=>setTimeout(resolve,40));}};
 await waitFor('event: call.scheduled');
 await waitFor(': keepalive');
 const attach=await context.request.post(origin+'/api/rtms/streams',{data:{meeting_id:meetingID,meeting_uuid:'proof-'+callID,rtms_stream_id:'proof-stream-'+callID}});
 assert.equal(attach.status(),200);
 assert.equal((await attach.json()).id,callID);
 const event=await context.request.post(origin+`/api/demo/calls/${callID}/events`,{data:{kind:'transcript',participant:{id:'speaker',name:'Opening speaker'},data:{text:'Opening words reach clients that connected early.',final:true}}});
 assert.equal(event.status(),201);
 await waitFor('Opening words reach clients that connected early.');
 await page.getByText('Opening words reach clients that connected early.',{exact:true}).waitFor();
 await page.getByRole('heading',{name:'Ready for clients to connect'}).waitFor({state:'hidden'});
 await page.screenshot({animations:'disabled',path:artifacts+'/live.png',fullPage:true});
 const stop=await context.request.post(origin+`/api/rtms/streams/proof-stream-${callID}/stop`,{data:{status:'stopped'}});
 assert.equal(stop.status(),200);
 await waitFor('event: end');await drain;
 const replay=await context.request.get(origin+`/api/calls/${callID}/stream`,{headers:{'Last-Event-ID':'2'}});
 const replayText=await replay.text();
 assert(replayText.includes('Opening words reach clients that connected early.'));
 assert(!replayText.includes('event: stream.started'));
 // A second UI-created call exercises cancellation while clients are waiting.
 await page.goto(origin+'/calls');
 await page.getByRole('button',{name:'Add scheduled call',exact:true}).click();
 await page.getByLabel('Zoom invitation or meeting link').fill(`https://zoom.us/j/${meetingID}`);
 await page.getByLabel('Call title').fill('Cancelled scheduled session');
 await page.getByRole('button',{name:'Add call',exact:true}).click();
 await page.getByRole('heading',{name:'Ready for clients to connect'}).waitFor();
 await page.getByRole('button',{name:'Cancel scheduled call',exact:true}).click();
 await page.getByText('Scheduled call cancelled',{exact:true}).waitFor();
 await page.screenshot({animations:'disabled',path:artifacts+'/cancelled.png',fullPage:true});
 assert.deepEqual(errors,[]);
 await writeFile(artifacts+'/client-stream.txt',received.trimEnd()+'\n');
 await writeFile(artifacts+'/result.json',JSON.stringify({origin,callID,meetingID,proof:'Local production binary with simulated incoming Zoom data; API-key client subscribed before start and received opening words on the same connection',events:received.match(/^event: .+$/gm),replayAfter:2,mobileOverflow:false,browserErrors:errors,cancellation:'UI client received cancellation and ended'},null,2)+'\n');
 await context.request.delete(origin+'/api/keys/'+key.key.id);
 console.log('PASS: add invitation → waiting UI and API-key client → same call live → opening transcript → replay → cancellation. Screenshots in '+artifacts);
} finally { await browser.close(); }
